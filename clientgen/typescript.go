// TypeScript returns a standalone fetch client. JSON, text and empty responses
// have typed Result values; other responses retain the native Response stream.
// File/form requests use browser-native FormData, URLSearchParams or BodyInit.
// Schema constraints remain server-enforced; this client supplies static types.
func TypeScript(document []byte) ([]byte, error) {
	d, err := parse(document)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by Trest. DO NOT EDIT.\n")
	for _, op := range d.websocketOperations {
		fmt.Fprintf(&b, "// Skipped %s: use a native WebSocket client for this WebSocket route.\n", op.ID)
	}
	b.WriteString(tsRuntime)
	b.WriteString(tsRealtimeRuntime)
	for _, name := range keys(d.Components.Schemas) {
		typ, err := d.tsType(d.Components.Schemas[name])
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "export type Schema%s = %s;\n", goName(name), typ)
	}
	for _, op := range d.operations {
		if err := d.tsDeclarations(&b, op); err != nil {
			return nil, err
		}
	}
	b.WriteString("\nexport class Client {\n private readonly baseURL: string;\n private readonly config: ClientOptions;\n constructor(baseURL: string, options: ClientOptions = {}) {\n const url = new URL(baseURL);\n if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) throw new Error('Invalid API base URL');\n this.baseURL = url.toString().replace(/\\/$/, ''); this.config = options;\n }\n")
	for _, op := range d.operations {
		d.tsMethod(&b, op)
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func (d *document) tsDeclarations(b *strings.Builder, op operation) error {
	fmt.Fprintf(b, "\nexport interface %sInput {\n", op.Export)
	for _, group := range []struct{ in, key string }{{"path", "path"}, {"query", "query"}, {"header", "headers"}, {"cookie", "cookies"}} {
		params := parameters(op, group.in)
		if len(params) == 0 {
			continue
		}
		optional := ""
		if !groupRequired(params) || group.in == "cookie" {
			optional = "?"
		}
		fmt.Fprintf(b, " %s%s: {\n", group.key, optional)
		for _, p := range params {
			typ, err := d.tsType(p.Schema)
			if err != nil {
				return err
			}
			optional = ""
			if !p.Required {
				optional = "?"
			}
			fmt.Fprintf(b, "  %s%s: %s;\n", jsQuote(p.Name), optional, typ)
		}
		b.WriteString(" };\n")
	}
	if op.Body != nil {
		typ := "BodyInit"
		switch op.BodyKind {
		case "application/json":
			var err error
			typ, err = d.tsType(op.BodyType)
			if err != nil {
				return err
			}
		case "application/x-www-form-urlencoded":
			typ = "URLSearchParams"
			if op.TypedForm {
				typ = op.Export + "Body | URLSearchParams"
			}
		case "multipart/form-data":
			typ = "FormData"
			if op.TypedForm {
				typ = op.Export + "Body | FormData"
			}
		case "text/plain":
			typ = "string"
		}
		optional := ""
		if !op.Body.Required {
			optional = "?"
		}
		fmt.Fprintf(b, " body%s: %s;\n", optional, typ)
	}
	b.WriteString("}\n")
	if op.TypedForm {
		fmt.Fprintf(b, "export interface %sBody {\n", op.Export)
		for _, field := range op.FormFields {
			typ, err := d.tsType(field.Schema)
			if err != nil {
				return err
			}
			if field.File {
				typ = "Blob"
				if field.ManyFiles {
					typ = "Array<Blob> | FileList"
				}
				if field.Nullable {
					typ += " | null"
				}
			}
			optional := ""
			if !field.Required {
				optional = "?"
			}
			fmt.Fprintf(b, " %s%s: %s;\n", jsQuote(field.Name), optional, typ)
		}
		b.WriteString("}\n")
	}
	if op.Stream != nil {
		typ, err := d.tsType(op.Stream.Schema)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "export type %sEvent = %s;\nexport type %sResult = EventStream<%sEvent>;\n", op.Export, typ, op.Export, op.Export)
		return nil
	}
	if op.Socket != nil {
		in, err := d.tsType(op.Socket.Input)
		if err != nil {
			return err
		}
		out, err := d.tsType(op.Socket.Output)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "export type %sMessage = %s;\nexport type %sOutput = %s;\nexport type %sResult = Socket<%sMessage,%sOutput>;\n", op.Export, in, op.Export, out, op.Export, op.Export, op.Export)
		return nil
	}
	if op.MixedOutput {
		variants := make([]string, 0, len(op.Outputs))
		for _, output := range op.Outputs {
			typ := "Response"
			switch output.Kind {
			case "application/json":
				var err error
				typ, err = d.tsType(output.Schema)
				if err != nil {
					return err
				}
			case "text/plain":
				typ = "string"
			case "empty":
				typ = "void"
			}
			variants = append(variants, fmt.Sprintf("{ status: %d; data: %s; headers: Headers }", output.Status, typ))
		}
		fmt.Fprintf(b, "export type %sResult = %s;\n", op.Export, strings.Join(variants, " | "))
		return nil
	}
	typ := "Response"
	switch op.OutputKind {
	case "application/json":
		var err error
		typ, err = d.tsType(op.OutputType)
		if err != nil {
			return err
		}
		typ = "Result<" + typ + ">"
	case "text/plain":
		typ = "Result<string>"
	case "empty":
		typ = "Result<void>"
	}
	fmt.Fprintf(b, "export type %sResult = %s;\n", op.Export, typ)
	return nil
}
func (d *document) tsMethod(b *strings.Builder, op operation) {
	def := ""
	if !inputRequired(op) {
		def = " = {}"
	}
	fmt.Fprintf(b, "\n async [%s](input: %sInput%s, options: RequestOptions = {}): Promise<%sResult> {\n", jsQuote(op.ID), op.Export, def, op.Export)
	fmt.Fprintf(b, " let path = %s;\n", jsQuote(op.Path))
	for _, p := range parameters(op, "path") {
		fmt.Fprintf(b, " if (input.path[%s] === undefined || input.path[%s] === null) throw new Error(%s);\n", jsQuote(p.Name), jsQuote(p.Name), jsQuote("Missing path parameter "+p.Name))
		fmt.Fprintf(b, " path = path.replace(%s, encodeURIComponent(String(input.path[%s])));\n", jsQuote("{"+p.Name+"}"), jsQuote(p.Name))
	}
	b.WriteString(" const query = new URLSearchParams();\n")
	for _, p := range parameters(op, "query") {
		fmt.Fprintf(b, " appendQuery(query, %s, input.query?.[%s]);\n", jsQuote(p.Name), jsQuote(p.Name))
	}
	b.WriteString(" const headers = new Headers(this.config.headers);\n new Headers(options.headers).forEach((value, key) => headers.set(key, value));\n")
	for _, p := range parameters(op, "header") {
		base, _ := d.resolve(p.Schema)
		if kind, _ := base.kind(); kind == "array" {
			fmt.Fprintf(b, " setHeaderArray(headers,%s,input.headers?.[%s]);\n", jsQuote(p.Name), jsQuote(p.Name))
			continue
		}
		fmt.Fprintf(b, " if (input.headers?.[%s] !== undefined && input.headers?.[%s] !== null) headers.set(%s, String(input.headers[%s]));\n", jsQuote(p.Name), jsQuote(p.Name), jsQuote(p.Name), jsQuote(p.Name))
	}
	if len(parameters(op, "cookie")) > 0 {
		b.WriteString(" if (input.cookies) {\n if (typeof document !== 'undefined') throw new Error('Browser cookies are managed by the browser; omit cookies and configure credentials');\n const cookies: string[] = [];\n")
		for _, p := range parameters(op, "cookie") {
			fmt.Fprintf(b, " if (input.cookies[%s] !== undefined && input.cookies[%s] !== null) { const value = String(input.cookies[%s]); if (/[^\\x21-\\x7E]|[;,\\\"\\\\]/.test(value)) throw new Error('Invalid cookie value'); cookies.push(%s + '=' + value); }\n", jsQuote(p.Name), jsQuote(p.Name), jsQuote(p.Name), jsQuote(p.Name))
		}
		b.WriteString(" if (cookies.length) headers.set('Cookie', cookies.join('; '));\n }\n")
	}
	if op.Socket != nil {
		fmt.Fprintf(b, " const target = new URL(this.baseURL + path + (query.size ? '?' + query.toString() : '')); target.protocol = target.protocol === 'https:' ? 'wss:' : 'ws:';\n return connectSocket<%sMessage,%sOutput>(target.toString(), headers, options.signal, this.config);\n }\n", op.Export, op.Export)
		return
	}
	b.WriteString(" let body: BodyInit | undefined;\n")
	if op.Body != nil {
		if op.Body.Required {
			b.WriteString(" if (input.body === undefined) throw new Error('Missing request body');\n")
		}
		switch op.BodyKind {
		case "application/json":
			b.WriteString(" if (input.body !== undefined) { body = JSON.stringify(input.body); headers.set('Content-Type', 'application/json'); }\n")
		case "multipart/form-data":
			if op.TypedForm {
				d.tsFormBody(b, op)
			} else {
				b.WriteString(" if (input.body !== undefined) { body = input.body; headers.delete('Content-Type'); }\n")
			}
		case "application/x-www-form-urlencoded":
			if op.TypedForm {
				d.tsFormBody(b, op)
			} else {
				b.WriteString(" if (input.body !== undefined) { body = input.body; headers.set('Content-Type', 'application/x-www-form-urlencoded'); }\n")
			}
		default:
			fmt.Fprintf(b, " if (input.body !== undefined) { body = input.body; headers.set('Content-Type', %s); }\n", jsQuote(op.BodyKind))
		}
	}
	fmt.Fprintf(b, " const response = await (this.config.fetch ?? globalThis.fetch)(this.baseURL + path + (query.size ? '?' + query.toString() : ''), { method: %s, headers, body, signal: options.signal, credentials: this.config.credentials, redirect: 'manual' });\n", jsQuote(op.Method))
	b.WriteString(" if (response.type === 'opaqueredirect') throw new Error('This runtime returned an opaque redirect; status and headers are unavailable. Use a server-side client to inspect redirects.');\n")
	statuses := []string{}
	for _, status := range op.Statuses {
		statuses = append(statuses, strconv.Itoa(status))
	}
	fmt.Fprintf(b, " if (![%s].includes(response.status)) throw await APIError.fromResponse(response, this.config.maxResponseBytes);\n", strings.Join(statuses, ","))
	if op.Stream != nil {
		fmt.Fprintf(b, " return new EventStream<%sEvent>(response,this.config.maxEventBytes);\n }\n", op.Export)
		return
	}
	if op.MixedOutput {
		d.tsVariantResponse(b, op)
		b.WriteString(" }\n")
		return
	}
	switch op.OutputKind {
	case "application/json":
		b.WriteString(" const text = await readText(response, this.config.maxResponseBytes);\n return { data: JSON.parse(text), status: response.status, headers: response.headers };\n")
	case "text/plain":
		b.WriteString(" return { data: await readText(response, this.config.maxResponseBytes), status: response.status, headers: response.headers };\n")
	case "empty":
		b.WriteString(" await response.body?.cancel();\n return { data: undefined, status: response.status, headers: response.headers };\n")
	default:
		b.WriteString(" return response;\n")
	}
	b.WriteString(" }\n")
}

func (d *document) tsVariantResponse(b *strings.Builder, op operation) {
	b.WriteString(" switch (response.status) {\n")
	for _, output := range op.Outputs {
		fmt.Fprintf(b, " case %d: {\n", output.Status)
		switch output.Kind {
		case "application/json":
			b.WriteString(" const data = JSON.parse(await readText(response, this.config.maxResponseBytes));\n")
		case "text/plain":
			b.WriteString(" const data = await readText(response, this.config.maxResponseBytes);\n")
		case "empty":
			b.WriteString(" await response.body?.cancel();\n const data = undefined;\n")
		default:
			b.WriteString(" const data = response;\n")
		}
		fmt.Fprintf(b, " return { data, status: %d, headers: response.headers };\n }\n", output.Status)
	}
	b.WriteString(" default: throw new Error('Unexpected declared response status');\n }\n")
}

func (d *document) tsFormBody(b *strings.Builder, op operation) {
	container := "URLSearchParams"
	if op.BodyKind == "multipart/form-data" {
		container = "FormData"
	}
	fmt.Fprintf(b, " if (input.body !== undefined) {\n if (input.body instanceof %s) { body = input.body; } else {\n const form = new %s();\n", container, container)
	for _, field := range op.FormFields {
		name := jsQuote(field.Name)
		if field.File {
			if field.ManyFiles {
				fmt.Fprintf(b, " for (const file of Array.from(input.body[%s] ?? [])) appendFile(form, %s, file);\n", name, name)
			} else {
				fmt.Fprintf(b, " if (input.body[%s] !== undefined && input.body[%s] !== null) appendFile(form, %s, input.body[%s]);\n", name, name, name, name)
			}
		} else {
			fmt.Fprintf(b, " appendForm(form, %s, input.body[%s]);\n", name, name)
		}
	}
	b.WriteString(" body = form;\n }\n")
	if op.BodyKind == "multipart/form-data" {
		b.WriteString(" headers.delete('Content-Type');\n")
	} else {
		b.WriteString(" headers.set('Content-Type', 'application/x-www-form-urlencoded');\n")
	}
	b.WriteString(" }\n")
}

const tsRuntime = `
export interface FieldError { path: string; code: string; message: string }
export interface Result<T> { data: T; status: number; headers: Headers }
export interface RequestOptions { signal?: AbortSignal; headers?: HeadersInit }
export interface ClientOptions { fetch?: typeof fetch; headers?: HeadersInit; credentials?: RequestCredentials; maxResponseBytes?: number; maxEventBytes?: number; maxMessageBytes?: number; maxQueuedMessages?: number; socketFactory?: SocketFactory }
export class APIError extends Error {
 readonly status: number; readonly code: string; readonly requestId: string; readonly fields: FieldError[];
 constructor(status: number, code: string, message: string, requestId = '', fields: FieldError[] = []) {
  super(message); this.name = 'APIError'; this.status = status; this.code = code; this.requestId = requestId; this.fields = fields;
 }
 static async fromResponse(response: Response, limit?: number): Promise<APIError> {
  const text = await readText(response, limit);
  let value: unknown; try { value = JSON.parse(text); } catch { value = null; }
  const data = value && typeof value === 'object' ? value as Record<string, unknown> : {};
  const fields = Array.isArray(data.fields) ? data.fields.filter((field): field is FieldError => !!field && typeof field === 'object' && typeof field.path === 'string' && typeof field.code === 'string' && typeof field.message === 'string') : [];
  return new APIError(response.status, typeof data.code === 'string' ? data.code : 'http_error', typeof data.message === 'string' ? data.message : response.statusText || 'Unexpected response status', typeof data.request_id === 'string' ? data.request_id : response.headers.get('X-Request-ID') ?? '', fields);
 }
}
function appendQuery(query: URLSearchParams, name: string, value: unknown): void {
 if (value === undefined || value === null) return;
 for (const item of Array.isArray(value) ? value : [value]) query.append(name, String(item));
}
function setHeaderArray(headers: Headers, name: string, value: unknown): void {
 if (value === undefined || value === null) return;
 if (!Array.isArray(value)) throw new Error('Header array ' + name + ' requires an array');
 const items = value.map(String); if (!items.length) return;
 for (const item of items) {
  if (item.includes(',') || /^[ \t]|[ \t]$/.test(item)) throw new Error('Header array ' + name + ' has an ambiguous item');
  if (/[\x00-\x08\x0A-\x1F\x7F]/.test(item)) throw new Error('Header array ' + name + ' has an invalid item');
 }
 headers.set(name, items.join(', '));
}
function appendForm(form: FormData | URLSearchParams, name: string, value: unknown): void {
 if (value === undefined || value === null) return;
 for (const item of Array.isArray(value) ? value : [value]) form.append(name, String(item));
}
function appendFile(form: FormData, name: string, file: Blob): void {
 if (!(file instanceof Blob)) throw new Error('Upload field ' + name + ' requires a File or Blob');
 form.append(name, file);
}
async function readText(response: Response, limit = 4 * 1024 * 1024): Promise<string> {
 if (!Number.isSafeInteger(limit) || limit <= 0) throw new Error('maxResponseBytes must be a positive safe integer');
 if (!response.body) return '';
 const reader = response.body.getReader(); const chunks: Uint8Array[] = []; let size = 0;
 try {
  for (;;) { const {done, value} = await reader.read(); if (done) break; size += value.byteLength; if (size > limit) { await reader.cancel(); throw new Error('Response exceeds size limit'); } chunks.push(value); }
 } finally { reader.releaseLock(); }
 const bytes = new Uint8Array(size); let offset = 0; for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.byteLength; }
 return new TextDecoder().decode(bytes);
}
`
