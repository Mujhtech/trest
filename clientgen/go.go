// Go returns a standalone standard-library client in packageName. Callers own
// successful raw response bodies. Typed JSON/text/error reads are bounded.
func Go(document []byte, packageName string) ([]byte, error) {
	if !validPackage(packageName) {
		return nil, fmt.Errorf("clientgen: invalid library package %q", packageName)
	}
	d, err := parse(document)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by Trest. DO NOT EDIT.\npackage %s\n", packageName)
	b.WriteString(goRuntime)
	b.WriteString(goRealtimeRuntime)
	for _, op := range d.websocketOperations {
		fmt.Fprintf(&b, "\n// Skipped %s: use a native WebSocket client for this WebSocket route.\n", op.ID)
	}
	for _, name := range keys(d.Components.Schemas) {
		typ, err := d.goType(d.Components.Schemas[name])
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\ntype Schema%s %s\n", goName(name), typ)
	}
	for _, op := range d.operations {
		if err := d.goDeclarations(&b, op); err != nil {
			return nil, err
		}
		d.goMethod(&b, op)
	}
	source, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("clientgen: format generated Go: %w", err)
	}
	return source, nil
}
func (d *document) goDeclarations(b *strings.Builder, op operation) error {
	fmt.Fprintf(b, "\n// %sInput contains the declared request fields.\ntype %sInput struct {\n", op.Export, op.Export)
	for _, group := range []struct{ in, key string }{{"path", "Path"}, {"query", "Query"}, {"header", "Headers"}, {"cookie", "Cookies"}} {
		params := parameters(op, group.in)
		if len(params) == 0 {
			continue
		}
		fmt.Fprintf(b, "%s %s%s\n", group.key, op.Export, group.key)
	}
	if op.Body != nil {
		typ := "io.Reader"
		switch op.BodyKind {
		case "application/json":
			var err error
			typ, err = d.goType(op.BodyType)
			if err != nil {
				return err
			}
			if !op.Body.Required {
				typ = pointer(typ)
			}
		case "application/x-www-form-urlencoded":
			typ = "url.Values"
		case "multipart/form-data":
			typ = "*MultipartBody"
		case "text/plain":
			typ = "string"
		}
		if op.TypedForm {
			typ = "*" + op.Export + "Body"
		}
		fmt.Fprintf(b, "Body %s\n", typ)
		if op.TypedForm {
			raw := "url.Values"
			if op.BodyKind == "multipart/form-data" {
				raw = "*MultipartBody"
			}
			fmt.Fprintf(b, "// RawBody accepts a native form instead of Body; provide only one.\nRawBody %s\n", raw)
		}
	}
	b.WriteString("}\n")
	for _, group := range []struct{ in, key string }{{"path", "Path"}, {"query", "Query"}, {"header", "Headers"}, {"cookie", "Cookies"}} {
		params := parameters(op, group.in)
		if len(params) == 0 {
			continue
		}
		fmt.Fprintf(b, "type %s%s struct {\n", op.Export, group.key)
		seen := map[string]bool{}
		for _, p := range params {
			field := goName(p.Name)
			if field == "" || seen[field] {
				return fmt.Errorf("clientgen: colliding parameter Go field %q", p.Name)
			}
			seen[field] = true
			typ, err := d.goType(p.Schema)
			if err != nil {
				return err
			}
			if !p.Required {
				typ = pointer(typ)
			}
			fmt.Fprintf(b, "%s %s\n", field, typ)
		}
		b.WriteString("}\n")
	}
	if op.TypedForm {
		fmt.Fprintf(b, "type %sBody struct {\n", op.Export)
		for _, field := range op.FormFields {
			typ, err := d.goType(field.Schema)
			if err != nil {
				return err
			}
			if field.File {
				typ = "UploadFile"
				if field.ManyFiles {
					typ = "[]UploadFile"
				}
				if field.Nullable {
					typ = pointer(typ)
				}
			}
			if !field.Required {
				typ = pointer(typ)
			}
			fmt.Fprintf(b, "%s %s\n", goName(field.Name), typ)
		}
		b.WriteString("}\n")
	}
	if op.Stream != nil {
		typ, err := d.goType(op.Stream.Schema)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "type %sEvent %s\n", op.Export, typ)
		return nil
	}
	if op.Socket != nil {
		in, err := d.goType(op.Socket.Input)
		if err != nil {
			return err
		}
		out, err := d.goType(op.Socket.Output)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "type %sMessage %s\ntype %sOutput %s\n", op.Export, in, op.Export, out)
		return nil
	}
	if op.MixedOutput {
		return d.goVariantDeclarations(b, op)
	}
	typ := "struct{}"
	switch op.OutputKind {
	case "application/json":
		var err error
		typ, err = d.goType(op.OutputType)
		if err != nil {
			return err
		}
	case "text/plain":
		typ = "string"
	case "empty":
	default:
		return nil
	}
	fmt.Fprintf(b, "type %sOutput %s\n", op.Export, typ)
	return nil
}
func (d *document) goMethod(b *strings.Builder, op operation) {
	raw := !op.MixedOutput && op.Stream == nil && op.Socket == nil && nativeOutput(op.OutputKind)
	returnType := "Result[" + op.Export + "Output]"
	if raw {
		returnType = "*http.Response"
	}
	if op.MixedOutput {
		returnType = op.Export + "Result"
	}
	if op.Stream != nil {
		returnType = "*EventStream[" + op.Export + "Event]"
	}
	if op.Socket != nil {
		returnType = "*Socket[" + op.Export + "Message," + op.Export + "Output]"
	}
	fmt.Fprintf(b, "\n// %s performs %s %s.\n", op.Export, op.Method, strings.ReplaceAll(op.Path, "\n", ""))
	if raw {
		b.WriteString("// The caller must close the returned response body.\n")
	}
	fmt.Fprintf(b, "func (c *Client) %s(ctx context.Context, input %sInput) (%s,error) {\n", op.Export, op.Export, returnType)
	zero := "zero"
	if raw || op.Stream != nil || op.Socket != nil {
		zero = "nil"
	} else {
		fmt.Fprintf(b, "var zero %s\n", returnType)
	}
	fmt.Fprintf(b, "path := %s\n", strconv.Quote(op.Path))
	for _, p := range parameters(op, "path") {
		fmt.Fprintf(b, "path = strings.ReplaceAll(path, %s, url.PathEscape(scalar(input.Path.%s)))\n", strconv.Quote("{"+p.Name+"}"), goName(p.Name))
	}
	b.WriteString("query := url.Values{}\nheaders := make(http.Header)\n")
	for _, p := range parameters(op, "query") {
		fmt.Fprintf(b, "addQuery(query, %s, input.Query.%s)\n", strconv.Quote(p.Name), goName(p.Name))
	}
	for _, p := range parameters(op, "header") {
		base, _ := d.resolve(p.Schema)
		if kind, _ := base.kind(); kind == "array" {
			fmt.Fprintf(b, "if err:=setHeaderArray(headers,%s,input.Headers.%s);err!=nil{return %s,err}\n", strconv.Quote(p.Name), goName(p.Name), zero)
			continue
		}
		fmt.Fprintf(b, "if values := values(input.Headers.%s); len(values)>0 { headers.Set(%s, values[0]) }\n", goName(p.Name), strconv.Quote(p.Name))
	}
	for _, p := range parameters(op, "cookie") {
		fmt.Fprintf(b, "if vals := values(input.Cookies.%s); len(vals)>0 { value := &http.Cookie{Name:%s, Value:vals[0]}; if value.Valid()!=nil {return %s, fmt.Errorf(\"invalid cookie\")}; cookie:=value.String(); if headers.Get(\"Cookie\")!=\"\" {cookie=headers.Get(\"Cookie\")+\"; \"+cookie};headers.Set(\"Cookie\",cookie) }\n", goName(p.Name), strconv.Quote(p.Name), zero)
	}
	if op.Socket != nil {
		fmt.Fprintf(b, "transport,err:=c.connectSocket(ctx,path,query,headers);if err!=nil{return nil,err};return &Socket[%sMessage,%sOutput]{Transport:transport,maxMessageBytes:c.MaxMessageBytes},nil\n}\n", op.Export, op.Export)
		return
	}
	b.WriteString("var body io.Reader\n")
	if op.Body != nil {
		switch op.BodyKind {
		case "application/json":
			optional := !op.Body.Required
			if optional {
				b.WriteString("if input.Body != nil {\n")
			}
			fmt.Fprintf(b, "encoded, err := json.Marshal(input.Body); if err != nil {return %s,fmt.Errorf(\"encode request: %%w\",err)}\nbody=bytes.NewReader(encoded)\nheaders.Set(\"Content-Type\",\"application/json\")\n", zero)
			if optional {
				b.WriteString("}\n")
			}
		case "application/x-www-form-urlencoded":
			if op.TypedForm {
				d.goFormBody(b, op, zero)
			} else {
				fmt.Fprintf(b, "encoded,err:=c.encodeForm(input.Body);if err!=nil{return %s,err};body=encoded\nheaders.Set(\"Content-Type\",\"application/x-www-form-urlencoded\")\n", zero)
			}
		case "multipart/form-data":
			if op.TypedForm {
				d.goFormBody(b, op, zero)
			} else {
				fmt.Fprintf(b, "if input.Body!=nil {encoded,contentType,err:=nativeMultipart(input.Body);if err!=nil{return %s,err};body=encoded;headers.Set(\"Content-Type\",contentType)}\n", zero)
				if op.Body.Required {
					fmt.Fprintf(b, "if body==nil{return %s,fmt.Errorf(\"request body required\")}\n", zero)
				}
			}
		case "text/plain":
			b.WriteString("body=strings.NewReader(input.Body)\nheaders.Set(\"Content-Type\",\"text/plain\")\n")
		default:
			b.WriteString("body=input.Body\nheaders.Set(\"Content-Type\",\"application/octet-stream\")\n")
			if op.Body.Required {
				fmt.Fprintf(b, "if body==nil{return %s,fmt.Errorf(\"request body required\")}\n", zero)
			}
		}
	}
	fmt.Fprintf(b, "response,err:=c.request(ctx,%s,path,query,headers,body)\nif err!=nil{return %s,err}\n", strconv.Quote(op.Method), zero)
	statuses := []string{}
	for _, status := range op.Statuses {
		statuses = append(statuses, strconv.Itoa(status))
	}
	fmt.Fprintf(b, "if err=c.checkResponse(response,[]int{%s});err!=nil{return %s,err}\n", strings.Join(statuses, ","), zero)
	if op.Stream != nil {
		fmt.Fprintf(b, "return newEventStream[%sEvent](response,c.MaxEventBytes)\n}\n", op.Export)
		return
	}
	if op.MixedOutput {
		d.goVariantResponse(b, op)
		return
	}
	if raw {
		b.WriteString("return response,nil\n}\n")
		return
	}
	fmt.Fprintf(b, "result:=Result[%sOutput]{Status:response.StatusCode,Header:response.Header.Clone()}\ndefer response.Body.Close()\n", op.Export)
	if op.OutputKind != "empty" {
		fmt.Fprintf(b, "data,err:=c.read(response.Body);if err!=nil{return %s,err}\n", zero)
		if op.OutputKind == "application/json" {
			fmt.Fprintf(b, "if err=json.Unmarshal(data,&result.Data);err!=nil{return %s,fmt.Errorf(\"decode response: %%w\",err)}\n", zero)
		} else {
			fmt.Fprintf(b, "result.Data=%sOutput(data)\n", op.Export)
		}
	}
	b.WriteString("return result,nil\n}\n")
}

func nativeOutput(kind string) bool {
	return kind != "application/json" && kind != "text/plain" && kind != "empty"
}

func variantName(op operation, output outputVariant) string {
	return op.Export + "Status" + strconv.Itoa(output.Status) + "Output"
}

func (d *document) goVariantDeclarations(b *strings.Builder, op operation) error {
	for _, output := range op.Outputs {
		typ := "struct{}"
		switch output.Kind {
		case "application/json":
			var err error
			typ, err = d.goType(output.Schema)
			if err != nil {
				return err
			}
		case "text/plain":
			typ = "string"
		case "empty":
		default:
			continue
		}
		fmt.Fprintf(b, "type %s %s\n", variantName(op, output), typ)
	}
	fmt.Fprintf(b, "// %sResult contains exactly one successful status variant.\ntype %sResult struct {\nStatus int\nHeader http.Header\n", op.Export, op.Export)
	for _, output := range op.Outputs {
		typ := "*" + variantName(op, output)
		if nativeOutput(output.Kind) {
			typ = "*http.Response"
			b.WriteString("// The caller must close this native response body when selected.\n")
		}
		fmt.Fprintf(b, "Status%d %s\n", output.Status, typ)
	}
	b.WriteString("}\n")
	for _, output := range op.Outputs {
		typ := variantName(op, output)
		if nativeOutput(output.Kind) {
			fmt.Fprintf(b, "func(r %sResult)As%d()(*http.Response,bool){return r.Status%d,r.Status==%d&&r.Status%d!=nil}\n", op.Export, output.Status, output.Status, output.Status, output.Status)
			continue
		}
		fmt.Fprintf(b, "func(r %sResult)As%d()(%s,bool){if r.Status!=%d||r.Status%d==nil{var zero %s;return zero,false};return *r.Status%d,true}\n", op.Export, output.Status, typ, output.Status, output.Status, typ, output.Status)
	}
	return nil
}

func (d *document) goVariantResponse(b *strings.Builder, op operation) {
	fmt.Fprintf(b, "result:=%sResult{Status:response.StatusCode,Header:response.Header.Clone()}\nswitch response.StatusCode{\n", op.Export)
	for _, output := range op.Outputs {
		fmt.Fprintf(b, "case %d:\n", output.Status)
		if nativeOutput(output.Kind) {
			fmt.Fprintf(b, "result.Status%d=response\nreturn result,nil\n", output.Status)
			continue
		}
		fmt.Fprintf(b, "defer response.Body.Close()\nvar value %s\n", variantName(op, output))
		if output.Kind != "empty" {
			b.WriteString("data,err:=c.read(response.Body);if err!=nil{return zero,err}\n")
			if output.Kind == "application/json" {
				b.WriteString("if err=json.Unmarshal(data,&value);err!=nil{return zero,fmt.Errorf(\"decode response: %w\",err)}\n")
			} else {
				fmt.Fprintf(b, "value=%s(data)\n", variantName(op, output))
			}
		}
		fmt.Fprintf(b, "result.Status%d=&value\nreturn result,nil\n", output.Status)
	}
	b.WriteString("default:response.Body.Close();return zero,fmt.Errorf(\"unexpected declared response status\")\n}\n}\n")
}

func (d *document) goFormBody(b *strings.Builder, op operation, zero string) {
	fmt.Fprintf(b, "if input.Body!=nil&&input.RawBody!=nil{return %s,fmt.Errorf(\"provide Body or RawBody, not both\")}\n", zero)
	b.WriteString("if input.Body!=nil {\n")
	if op.BodyKind == "multipart/form-data" {
		b.WriteString("encoded,contentType,err:=c.encodeMultipart(ctx,func(form *multipart.Writer)error{\n")
		for _, field := range op.FormFields {
			access := "input.Body." + goName(field.Name)
			if !field.File {
				fmt.Fprintf(b, "for _,value:=range values(%s){if err:=form.WriteField(%s,value);err!=nil{return err}}\n", access, strconv.Quote(field.Name))
				continue
			}
			if field.Nullable || !field.Required {
				fmt.Fprintf(b, "if %s!=nil {\n", access)
				access = "*" + access
			}
			if field.ManyFiles {
				fmt.Fprintf(b, "for _,file:=range %s {if err:=writeUpload(ctx,form,%s,file);err!=nil{return err}}\n", access, strconv.Quote(field.Name))
			} else {
				fmt.Fprintf(b, "if err:=writeUpload(ctx,form,%s,%s);err!=nil{return err}\n", strconv.Quote(field.Name), access)
			}
			if field.Nullable || !field.Required {
				b.WriteString("}\n")
			}
		}
		fmt.Fprintf(b, "return nil\n});if err!=nil{return %s,fmt.Errorf(\"encode multipart request: %%w\",err)}\nbody=encoded;headers.Set(\"Content-Type\",contentType)\n", zero)
		fmt.Fprintf(b, "}else if input.RawBody!=nil {encoded,contentType,err:=nativeMultipart(input.RawBody);if err!=nil{return %s,err};body=encoded;headers.Set(\"Content-Type\",contentType)}\n", zero)
	} else {
		b.WriteString("form:=url.Values{}\n")
		for _, field := range op.FormFields {
			fmt.Fprintf(b, "addQuery(form,%s,input.Body.%s)\n", strconv.Quote(field.Name), goName(field.Name))
		}
		fmt.Fprintf(b, "encoded,err:=c.encodeForm(form);if err!=nil{return %s,err};body=encoded\n", zero)
		fmt.Fprintf(b, "}else if input.RawBody!=nil {encoded,err:=c.encodeForm(input.RawBody);if err!=nil{return %s,err};body=encoded}\n", zero)
		b.WriteString("if body!=nil{headers.Set(\"Content-Type\",\"application/x-www-form-urlencoded\")}\n")
	}
	if op.Body.Required {
		fmt.Fprintf(b, "if body==nil{return %s,fmt.Errorf(\"request body required\")}\n", zero)
	}
}

