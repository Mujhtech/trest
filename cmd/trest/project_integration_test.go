func newProject(t *testing.T) string {
	t.Helper()
	directory := filepath.Join(t.TempDir(), "app")
	var out, diag bytes.Buffer
	if code := runNew([]string{directory}, &out, &diag); code != 0 {
		t.Fatalf("new exit=%d: %s", code, diag.String())
	}
	return directory
}
func projectGo(t *testing.T, directory string, args ...string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	command := exec.CommandContext(ctx, "go", args...)
	command.Dir = directory
	command.Env = projectEnvironment("")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("go %v: %v\n%s", args, err, output)
	}
}
func TestScaffoldBuildExportsAndGeneratedClient(t *testing.T) {
	directory := newProject(t)
	projectGo(t, directory, "test", "-race", "./...")
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	var diagnostics bytes.Buffer
	document, err := exportProject(ctx, directory, "./cmd/server", "openapi", &diagnostics)
	if err != nil {
		t.Fatalf("export: %v %s", err, diagnostics.String())
	}
	var spec map[string]any
	if err := json.Unmarshal(document, &spec); err != nil {
		t.Fatal(err)
	}
	if spec["paths"].(map[string]any)["/greet/{name}"] == nil {
		t.Fatalf("missing typed route: %s", document)
	}
	manifest, err := exportProject(ctx, directory, "./cmd/server", "manifest", &diagnostics)
	if err != nil || !bytes.Contains(manifest, []byte("trest.app.v1")) {
		t.Fatalf("manifest: %s %v %s", manifest, err, diagnostics.String())
	}
	generated, err := generateClient(document, "go", "client")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(directory, "client"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := writeGenerated(filepath.Join(directory, "client", "client.go"), generated, false, false); err != nil {
		t.Fatal(err)
	}
	projectGo(t, directory, "test", "./...")
}

type liveDevOutput struct{ events chan string }

func (w liveDevOutput) Write(data []byte) (int, error) {
	var event struct {
		Event string `json:"event"`
	}
	if json.Unmarshal(data, &event) == nil && event.Event != "" {
		w.events <- event.Event
	}
	return len(data), nil
}

type synchronizedBuffer struct {
	mu     sync.Mutex
	buffer bytes.Buffer
}

func (b *synchronizedBuffer) Write(data []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buffer.Write(data)
}
func (b *synchronizedBuffer) String() string {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buffer.String()
}

func TestGenericDevReloadGenerationAndShutdown(t *testing.T) {
	directory := newProject(t)
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	address := listener.Addr().String()
	if err := listener.Close(); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	events := make(chan string, 32)
	completed := make(chan int, 1)
	var diagnostics synchronizedBuffer
	go func() {
		completed <- runDev(ctx, []string{"--dir", directory, "--addr", address, "--watch", "--poll", "50ms", "--client", "ts", "--client-out", "client.ts"}, liveDevOutput{events}, &diagnostics)
	}()
	defer func() {
		cancel()
		select {
		case code := <-completed:
			if code != 0 {
				t.Errorf("dev exit=%d: %s", code, diagnostics.String())
			}
		case <-time.After(10 * time.Second):
			t.Error("dev did not shut down")
		}
	}()
	waitEvent := func(wanted string) {
		t.Helper()
		timer := time.NewTimer(45 * time.Second)
		defer timer.Stop()
		for {
			select {
			case event := <-events:
				if event == wanted {
					return
				}
			case code := <-completed:
				completed <- code
				t.Fatalf("dev exited before %s: %d %s", wanted, code, diagnostics.String())
			case <-timer.C:
				t.Fatalf("timed out waiting for %s: %s", wanted, diagnostics.String())
			}
		}
	}
	client := &http.Client{Timeout: time.Second, Transport: &http.Transport{Proxy: nil}}
	defer client.CloseIdleConnections()
	assertResponse := func(want string) {
		t.Helper()
		response, err := client.Get("http://" + address + "/")
		if err != nil {
			t.Fatal(err)
		}
		body, err := io.ReadAll(response.Body)
		closeErr := response.Body.Close()
		if err != nil || closeErr != nil || response.StatusCode != 200 || string(body) != want {
			t.Fatalf("response %d %q errors %v %v", response.StatusCode, body, err, closeErr)
		}
	}
	waitEvent("ready")
	assertResponse("Hello from Trest")
	generated, err := os.ReadFile(filepath.Join(directory, "client.ts"))
	if err != nil || !bytes.HasPrefix(generated, []byte("// Code generated by Trest.")) {
		t.Fatalf("client missing: %v", err)
	}
	sourcePath := filepath.Join(directory, "cmd", "server", "main.go")
	source, err := os.ReadFile(sourcePath)
	if err != nil {
		t.Fatal(err)
	}
	updated := strings.Replace(string(source), "Hello from Trest", "Hello revised", 1)
	if err := os.WriteFile(sourcePath, []byte(updated), 0o644); err != nil {
		t.Fatal(err)
	}
	waitEvent("ready")
	assertResponse("Hello revised")
	broken := filepath.Join(directory, "cmd", "server", "broken.go")
	if err := os.WriteFile(broken, []byte("package main\nfunc broken("), 0o644); err != nil {
		t.Fatal(err)
	}
	waitEvent("build_failed")
	assertResponse("Hello revised")
	if !strings.Contains(diagnostics.String(), "broken.go") {
		t.Fatal("compiler diagnostic was hidden")
	}
	if err := os.Remove(broken); err != nil {
		t.Fatal(err)
	}
	waitEvent("ready")
	assertResponse("Hello revised")
}
