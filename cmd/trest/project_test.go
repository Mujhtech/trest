func TestNewCreatesIndependentProjectWithoutOverwriting(t *testing.T) {
	destination := filepath.Join(t.TempDir(), "my-app")
	var output, diagnostics bytes.Buffer
	if code := run(context.Background(), []string{"new", destination}, &output, &diagnostics); code != 0 {
		t.Fatalf("new exit=%d: %s", code, diagnostics.String())
	}
	for _, name := range []string{"cmd/server/main.go", "cmd/server/main_test.go"} {
		data, err := os.ReadFile(filepath.Join(destination, name))
		if err != nil {
			t.Fatal(err)
		}
		if _, err := parser.ParseFile(token.NewFileSet(), name, data, parser.AllErrors); err != nil {
			t.Fatalf("invalid generated Go: %v", err)
		}
	}
	module, err := os.ReadFile(filepath.Join(destination, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(module, []byte("module example.local/my-app")) || !bytes.Contains(module, []byte("replace github.com/mujhtech/trest =>")) {
		t.Fatalf("module=%s", module)
	}
	if code := run(context.Background(), []string{"new", destination}, &output, &diagnostics); code != 1 {
		t.Fatalf("existing directory accepted: %d", code)
	}
	after, err := os.ReadFile(filepath.Join(destination, "go.mod"))
	if err != nil || !bytes.Equal(after, module) {
		t.Fatal("existing project was changed")
	}
}

func TestNewRejectsInvalidModuleBeforeWriting(t *testing.T) {
	for _, module := range []string{"../bad", "example.com/../bad", "example.com/x\nreplace foo => bar", "/absolute", "-flag"} {
		t.Run(module, func(t *testing.T) {
			destination := filepath.Join(t.TempDir(), "app")
			var out, diag bytes.Buffer
			if code := runNew([]string{"--module", module, destination}, &out, &diag); code != 2 {
				t.Fatalf("invalid module accepted: %d %s", code, diag.String())
			}
			if _, err := os.Stat(destination); !os.IsNotExist(err) {
				t.Fatal("invalid module created directory")
			}
		})
	}
}

func TestClientGenerationRequiresExplicitOverwrite(t *testing.T) {
	dir := t.TempDir()
	spec := filepath.Join(dir, "openapi.json")
	output := filepath.Join(dir, "client.ts")
	contract := []byte(`{"openapi":"3.1.1","paths":{"/hello":{"get":{"operationId":"hello","responses":{"200":{"description":"OK","content":{"text/plain":{"schema":{"type":"string"}}}}}}}}}`)
	if err := os.WriteFile(spec, contract, 0o600); err != nil {
		t.Fatal(err)
	}
	var out, diag bytes.Buffer
	args := []string{"--spec", spec, "--lang", "ts", "--out", output}
	if code := runClient(args, &out, &diag); code != 0 {
		t.Fatalf("generation failed: %s", diag.String())
	}
	first, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(first, []byte("// Code generated by Trest.")) || !bytes.Contains(first, []byte("hello")) {
		t.Fatalf("unexpected generated file: %s", first)
	}
	if code := runClient(args, &out, &diag); code != 1 {
		t.Fatalf("unapproved overwrite=%d", code)
	}
	if code := runClient(append(args, "--overwrite"), &out, &diag); code != 0 {
		t.Fatalf("explicit overwrite failed: %s", diag.String())
	}
	second, err := os.ReadFile(output)
	if err != nil || !bytes.Equal(first, second) {
		t.Fatal("generation is not deterministic")
	}
	goOutput := filepath.Join(dir, "client.go")
	if code := runClient([]string{"--spec", spec, "--lang", "go", "--package", "api", "--out", goOutput}, &out, &diag); code != 0 {
		t.Fatalf("Go generation failed: %s", diag.String())
	}
	data, err := os.ReadFile(goOutput)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), goOutput, data, parser.AllErrors); err != nil {
		t.Fatal(err)
	}
}

func TestGeneratedWritesAreAtomicAndRejectSymlinks(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "client.ts")
	if err := os.WriteFile(path, []byte("user code"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := writeGenerated(path, []byte("replacement"), true, true); err == nil {
		t.Fatal("watcher replaced an unmarked file")
	}
	data, err := os.ReadFile(path)
	if err != nil || string(data) != "user code" {
		t.Fatal("existing code changed")
	}
	link := filepath.Join(dir, "link.ts")
	if err := os.Symlink(path, link); err != nil {
		t.Fatal(err)
	}
	if err := writeGenerated(link, []byte("replacement"), true, false); err == nil {
		t.Fatal("replaced a symlink")
	}
	marked := []byte("// Code generated by Trest. DO NOT EDIT.\nold\n")
	if err := os.WriteFile(path, marked, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := writeGenerated(path, []byte("// Code generated by Trest. DO NOT EDIT.\nnew\n"), true, true); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if strings.HasPrefix(entry.Name(), ".trest-generated-") {
			t.Fatal("temporary output not cleaned")
		}
	}
}

func TestUnchangedGenerationPreservesSourceFingerprint(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "client.go")
	data := []byte("// Code generated by Trest. DO NOT EDIT.\npackage client\n")
	if err := writeGenerated(path, data, false, false); err != nil {
		t.Fatal(err)
	}
	past := time.Unix(1700000000, 0)
	if err := os.Chtimes(path, past, past); err != nil {
		t.Fatal(err)
	}
	before, err := sourceFingerprint(dir)
	if err != nil {
		t.Fatal(err)
	}
	if err := writeGenerated(path, data, true, true); err != nil {
		t.Fatal(err)
	}
	after, err := sourceFingerprint(dir)
	if err != nil {
		t.Fatal(err)
	}
	if before != after {
		t.Fatal("unchanged generation would trigger another source rebuild")
	}
}

